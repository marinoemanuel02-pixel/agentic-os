// src/data/assets.ts: the only way media reach the picture (components take an asset id, never a path).
export function registryText(rows) {
  const items = [...rows].sort((a, b) => a.id.localeCompare(b.id)).map(r => {
    const d = (r.derivatives || [])[0];
    return `  "${r.id}": { "src": "${String(d ? d.path : '').replaceAll('\\', '/')}", "kind": "${r.kind}" }`;
  });
  return `// generated by aos asset registry; do not edit\nexport const ASSETS = {\n${items.join(',\n')}\n} as const;\n`;
}

const tagged = r => r.basis === 'fair-use' || r.basis === 'capture';

// src/data/asset-uses.ts: each use's media window and sound, plus the source tag text for fair-use and capture rows.
export function usesText(rows) {
  const items = [...rows].sort((a, b) => a.id.localeCompare(b.id)).map(r => {
    const uses = (r.uses || []).map(u => `"${u.use}": { "mediaFrom": ${u.mediaFrom}, "mediaTo": ${u.mediaTo}, "audio": "${u.audio}", "credit": ${tagged(r) ? JSON.stringify(r.credit) : 'null'} }`);
    return `  "${r.id}": { ${uses.join(', ')} }`;
  });
  return `// generated by aos asset registry; do not edit\nexport const USES: Record<string, Record<string, { mediaFrom: number; mediaTo: number; audio: string; credit: string | null }>> = {\n${items.join(',\n')}\n};\n`;
}

// One generated label claim per tagged asset, so screen-text coverage (R24) includes every source tag.
export function screenEntries(rows) {
  return rows.filter(r => tagged(r) && (r.uses || []).length)
    .map(r => ({texts: [r.credit], kind: 'label', asset: r.id, sources: [], reviewed: false, generated: true}));
}

// Replace only generated entries; an unchanged tag keeps its review state, authored entries stay as they are.
export function mergeScreen(claims, entries) {
  const old = (claims.screen || []).filter(s => s.generated);
  const kept = (claims.screen || []).filter(s => !s.generated);
  const merged = entries.map(e => {
    const prev = old.find(s => s.asset === e.asset && JSON.stringify(s.texts) === JSON.stringify(e.texts));
    return prev ? {...e, reviewed: prev.reviewed} : e;
  });
  return {...claims, screen: [...kept, ...merged]};
}
