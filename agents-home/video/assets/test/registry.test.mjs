// The generated registry, uses table and source-tag claims (the only way imported media reach the picture).
import assert from 'node:assert/strict';
import {test} from 'node:test';
import {usesText, screenEntries, mergeScreen} from '../lib/registry.mjs';

const rows = [
  {id: 'a01', basis: 'license', credit: 'Video by Ana on Pexels', uses: [{use: 'u1', mediaFrom: 0, mediaTo: 8, audio: 'muted'}]},
  {id: 'a05', basis: 'fair-use', credit: 'Source: Lab demo, 2026-09-09', uses: [{use: 'u1', mediaFrom: 0, mediaTo: 3, audio: 'muted'}, {use: 'u2', mediaFrom: 3, mediaTo: 5, audio: 'subject'}]},
  {id: 'a06', basis: 'capture', credit: 'Source: product.example, captured 2026-10-07', uses: [{use: 'u1', mediaFrom: 0, mediaTo: 1, audio: 'muted'}]},
];

test('usesText carries a source tag only for fair-use and capture rows', () => {
  const t = usesText(rows);
  assert.match(t, /"a01": \{ "u1": \{ "mediaFrom": 0, "mediaTo": 8, "audio": "muted", "credit": null \} \}/);
  assert.match(t, /"a05": \{ "u1": \{ "mediaFrom": 0, "mediaTo": 3, "audio": "muted", "credit": "Source: Lab demo, 2026-09-09" \}, "u2"/);
  assert.match(t, /^\/\/ generated by aos asset registry/);
});

test('screenEntries makes one generated label claim per tagged asset', () => {
  assert.deepEqual(screenEntries(rows), [
    {texts: ['Source: Lab demo, 2026-09-09'], kind: 'label', asset: 'a05', sources: [], reviewed: false, generated: true},
    {texts: ['Source: product.example, captured 2026-10-07'], kind: 'label', asset: 'a06', sources: [], reviewed: false, generated: true}]);
});

test('mergeScreen replaces only generated entries and keeps authored ones and their review state', () => {
  const claims = {screen: [{texts: ['As of 6 Oct'], kind: 'label', sources: ['C1'], reviewed: true},
    {texts: ['old tag'], kind: 'label', asset: 'a99', generated: true, reviewed: true, sources: []},
    {texts: ['Source: Lab demo, 2026-09-09'], kind: 'label', asset: 'a05', generated: true, reviewed: true, sources: []}]};
  const out = mergeScreen(claims, screenEntries(rows)).screen;
  assert.equal(out[0].texts[0], 'As of 6 Oct');
  assert.equal(out.filter(s => s.generated).length, 2);
  assert.equal(out.find(s => s.asset === 'a05').reviewed, true, 'an unchanged tag keeps its review');
  assert.equal(out.find(s => s.asset === 'a06').reviewed, false);
  assert.ok(!out.some(s => s.asset === 'a99'));
});
